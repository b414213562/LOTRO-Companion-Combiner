using System.Xml;


public struct PaperItemCategory
{
    public int code = -1;
    public string name = "MISSING_NAME";
    public Dictionary<string, string> nameTranslations = new Dictionary<string, string>();

    public static Dictionary<string, string> unknownCategory = new Dictionary<string, string>
    {
        { "de", "In TitanBar unbekannt" },
        { "en", "Unknown to TitanBar" },
        { "fr", "Inconnu de TitanBar" },
    };

    public PaperItemCategory()
    {
    }

    public static PaperItemCategory FromXml(XmlReader reader)
    {
        var paperItemCategory = new PaperItemCategory();

        var code = reader.GetAttribute("code");
        if (code != null) { _ = int.TryParse(code, out paperItemCategory.code); }

        var name = reader.GetAttribute("name");
        if (name != null) { paperItemCategory.name = name; }

        return paperItemCategory;
    }

    public static List<PaperItemCategory> GetPaperItemCategories(string paperItemCategoryFile)
    {
        var result = new List<PaperItemCategory>();

        using var reader = XmlReader.Create(paperItemCategoryFile);

        while (reader.Read())
        {
            switch (reader.NodeType)
            {
                case XmlNodeType.Element:
                    if (reader.Name == "entry")
                    {
                        var name = reader.GetAttribute("name") ?? "";
                        if (name.StartsWith("key:"))
                        {
                            var newPaperItemCategory = FromXml(reader);
                            result.Add(newPaperItemCategory);
                        }
                    }
                    break;
            }
        }

        return result;
    }

    public static void AddTranslations(string lorePath, string lang, List<PaperItemCategory> paperItemCategories)
    {
        //   lore/labels/de/enum-PaperItemCategory.xml
        //   lore/labels/en/enum-PaperItemCategory.xml
        //   lore/labels/fr/enum-PaperItemCategory.xml

        var lookup = new Dictionary<string, PaperItemCategory>();
        foreach (var category in paperItemCategories)
        {
            lookup[category.name] = category;
        }

        var itemsFile = Path.Combine(lorePath, "labels", lang, "enum-PaperItemCategory.xml");
        using var reader = XmlReader.Create(itemsFile);

        while (reader.Read())
        {
            switch (reader.NodeType)
            {
                case XmlNodeType.Element:
                    if (reader.Name == "label")
                    {
                        var key = reader.GetAttribute("key") ?? "";
                        if (lookup.ContainsKey(key))
                        {
                            var value = reader.GetAttribute("value") ?? "MISSING_TRANSLATION";
                            lookup[key].nameTranslations[lang] = value;
                        }
                    }
                    break;
            }
        }
    }

    public static void WriteLanguageLua(List<PaperItemCategory> paperItemCategories, string lang)
    {
        var time = DateTime.UtcNow.ToString("yyyy-MM-dd HH:mm:ss");

        var path = @"C:\Users\bkckx\Documents\The Lord of the Rings Online\Plugins\HabnaPlugins\TitanBar\Locale";
        var fileName = Path.Combine(path, $"WalletItemCategories_{lang}.lua");

        using var file = new StreamWriter(fileName);
        file.WriteLine($"-- auto-generated by Cube's TitanBarWalletItemsGenerator tool at {time} UTC");
        file.WriteLine("_G.WalletItemCategories = {");

        foreach (var category in paperItemCategories)
        {
            var name = category.nameTranslations[lang];
            name = name.Replace("\\q", "\\\"");

            file.WriteLine($"  [{category.code}] = \"{name}\";");
        }

        file.WriteLine("};");
        file.WriteLine("");

        file.WriteLine($"_G.WalletItemCategoryUnknown = \"{unknownCategory[lang]}\";");
        file.WriteLine("");

    }



}

public struct PaperItem
{
    public long id = -1;
    public string name = "MISSING_NAME";
    public Dictionary<string, string> nameTranslations = new();
    public int itemClass = -1;
    public int category = -1;
    public bool shared = false;
    public bool old = false;
    public long icon = 0x410D79F6; // Question mark over shield

    public PaperItem()
    {
    }

    public static PaperItem FromXml(XmlReader reader)
    {
        var paperItem = new PaperItem();

        var id = reader.GetAttribute("identifier");
        if (id != null) { _ = long.TryParse(id, out paperItem.id); }

        var name = reader.GetAttribute("name");
        if (name != null) { paperItem.name = name; }

        var itemClass = reader.GetAttribute("itemClass");
        if (itemClass != null) { _ = int.TryParse(itemClass, out paperItem.itemClass); }

        var category = reader.GetAttribute("category");
        if (category != null) { _ = int.TryParse(category, out paperItem.category); }

        var shared = reader.GetAttribute("shared");
        if (shared != null) { _ = bool.TryParse(shared, out paperItem.shared); }

        var old = reader.GetAttribute("old");
        if (id == "1879218745")
        {
            old = "true";
        }
        if (old != null) { _ = bool.TryParse(old, out paperItem.old); }

        var iconId = reader.GetAttribute("iconId");
        if (iconId != null) { _ = long.TryParse(iconId, out paperItem.icon); }

        return paperItem;
    }

    public static List<PaperItem> GetPaperItems(string paperItemsFile)
    {
        var result = new List<PaperItem>();

        using var reader = XmlReader.Create(paperItemsFile);

        while (reader.Read())
        {
            switch (reader.NodeType)
            {
                case XmlNodeType.Element:
                    if (reader.Name == "paperItem")
                    {
                        var newPaperItem = FromXml(reader);
                        result.Add(newPaperItem);
                    }
                    break;
            }
        }

        return result;
    }

    public static void WriteNonLanguageLua(
        List<PaperItem> paperItems,
        List<PaperItemCategory> paperItemCategories)
    {
        var time = DateTime.UtcNow.ToString("yyyy-MM-dd HH:mm:ss");
        var path = @"C:\Users\bkckx\Documents\The Lord of the Rings Online\Plugins\HabnaPlugins\TitanBar\Data";
        var fileName = Path.Combine(path, "WalletItems.lua");
        using var file = new StreamWriter(fileName);
        file.WriteLine($"-- auto-generated by Cube's TitanBarWalletItemsGenerator tool at {time} UTC");
        file.WriteLine("_G.WalletItems = {");

        foreach (var item in paperItems)
        {
            var shared = item.shared ? "[\"shared\"] = true; ": "";
            var old = item.old ? "[\"old\"] = true; " : "";
            var icon = "[\"icon\"] = {item.icon}; ";
            icon = ""; // Not using this for now.

            var itemIdHex = item.id.ToString("x");
            var imageIdHex = item.icon.ToString("x");

            file.WriteLine($"  [{item.id}] = {{ [\"itemClass\"] = {item.itemClass}; [\"category\"] = {item.category}; {shared}{old}{icon}}}; -- {item.name}");
        }

        file.WriteLine("};");
        file.WriteLine("");

        // write the used categories:
        var usedCategories = new List<int>();
        foreach (var category in paperItemCategories)
        {
            var items = new List<PaperItem>();
            foreach (var item in paperItems)
            {
                if (item.category != category.code) continue;
                if (item.old) continue;

                items.Add(item);
            }

            if (items.Count > 0)
            {
                usedCategories.Add(category.code);
            }
        }

        // in-game order:
        //   9 = Coin
        //   13 = Festivals and Events
        //   15 = Landscape
        //   12 = Taxidermy
        //   8 = Other
        //   10 = Instances and Skirmishes
        //   11 = Item Advancement
        //   14 = Crafting
        //   6 = Currency
        var i = 0;
        var inGameOrderCategories = new List<int> { 9, 13, 15, 12, 8, 10, 11, 14, 6 };

        file.WriteLine("_G.WalletUsedCategories = {");

        foreach (var inGameOrderCategory in inGameOrderCategories)
        {
            ++i;
            file.WriteLine($"  [{i}] = {inGameOrderCategory}; -- {paperItemCategories.First(c => c.code == inGameOrderCategory).nameTranslations["en"]}");
        }

        foreach (var usedCategory in usedCategories)
        {
            if (!inGameOrderCategories.Contains(usedCategory))
            {
                file.WriteLine($"  [{i}] = {usedCategory}; -- {paperItemCategories.First(c => c.code == usedCategory).nameTranslations["en"]}");
            }
        }
        file.WriteLine("};");
        file.WriteLine("");
    }

    public static void WriteLanguageLua(
