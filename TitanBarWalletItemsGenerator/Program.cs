internal class Program
{

    private static void Main(string[] args)
    {
        var path = @"C:\dev\_\lotro-data\lore";
        if (args.Length > 0)
        {
            path = args[1];
        }

        // Load paperItems.xml:
        var paperItemsFile = Path.Combine(path, "paperItems.xml");
        var paperItems = PaperItem.GetPaperItems(paperItemsFile);

        // Load Paper Items labels:
        PaperItem.AddTranslations(path, "de", paperItems);
        PaperItem.AddTranslations(path, "en", paperItems);
        PaperItem.AddTranslations(path, "fr", paperItems);

        // Load categories
        var paperItemCategoryFile = Path.Combine(path, "enums", "PaperItemCategory.xml");
        var paperItemCategories = PaperItemCategory.GetPaperItemCategories(paperItemCategoryFile);

        // Load Paper Item Categories labels:
        PaperItemCategory.AddTranslations(path, "de", paperItemCategories);
        PaperItemCategory.AddTranslations(path, "en", paperItemCategories);
        PaperItemCategory.AddTranslations(path, "fr", paperItemCategories);

        // Generate the files TitanBar needs:
        // Central file without any translations
        // One translations file each for de, en, and fr.
        PaperItem.WriteNonLanguageLua(paperItems, paperItemCategories);

        var languages = new List<string> { "de", "en", "fr" };

        foreach ( var language in languages )
        {
            PaperItem.WriteByCategoryLanguageLua(paperItems, paperItemCategories, language);
            PaperItem.WriteLanguageLua(paperItems, language);
            PaperItemCategory.WriteLanguageLua(paperItemCategories, language);
        }
        // 

        Console.WriteLine("Hello, World!");
    }
