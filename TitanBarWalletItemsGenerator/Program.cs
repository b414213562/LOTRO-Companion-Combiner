    public static void WriteByCategoryLanguageLua(
        List<PaperItem> paperItems,
        List<PaperItemCategory> paperItemCategories,
        string lang)
    {
        var time = DateTime.UtcNow.ToString("yyyy-MM-dd HH:mm:ss");

        var path = @"C:\Users\bkckx\Documents\The Lord of the Rings Online\Plugins\HabnaPlugins\TitanBar\Locale";
        var fileName = Path.Combine(path, $"WalletItemsByCategory_{lang}.lua");

        using var file = new StreamWriter(fileName);
        file.WriteLine($"-- auto-generated by Cube's TitanBarWalletItemsGenerator tool at {time} UTC");
        file.WriteLine("_G.WalletItemsByCategories = {");

        foreach (var category in paperItemCategories)
        {
            var items = new List<PaperItem>();
            foreach (var item in paperItems)
            {
                if (item.category != category.code) continue;
                if (item.old) continue;

                items.Add(item);
            }

            if (items.Count > 0)
            {
                items = items.OrderBy(item => item.nameTranslations[lang]).ToList();

                file.WriteLine($"  [{category.code}] = {{ -- {category.nameTranslations["en"]}");
                var i = 0;
                foreach (var item in items)
                {
                    ++i;
                    var name = item.nameTranslations[lang];
                    name = name.Replace("\\q", "\\\"");

                    // Example:
                    // _G.WalletItems[1879155768]["name"] = "Skirmish Mark";
                    file.WriteLine($"    [{i}] = {item.id}; -- {name}");
                }
                file.WriteLine("  };");
            }

        }

        file.WriteLine("};");
        file.WriteLine("");

    }

    public static void AddTranslations(
        string lorePath,
        string lang,
        List<PaperItem> paperItems)
    {
        //   lore/labels/de/items.xml
        //   lore/labels/en/items.xml
        //   lore/labels/fr/items.xml

        var lookup = new Dictionary<long, PaperItem>();
        foreach (var paperItem in paperItems)
        {
            lookup[paperItem.id] = paperItem;
        }

        var itemsFile = Path.Combine(lorePath, "labels", lang, "items.xml");
        using var reader = XmlReader.Create(itemsFile);

        while (reader.Read())
        {
            switch (reader.NodeType)
            {
                case XmlNodeType.Element:
                    if (reader.Name == "label")
                    {
                        var key = reader.GetAttribute("key");
                        long id = 0;
                        if (key != null)
                        {
                            _ = long.TryParse(key, out id);
                        }
                        if (lookup.ContainsKey(id))
                        {
                            var value = reader.GetAttribute("value") ?? "MISSING_TRANSLATION";
                            lookup[id].nameTranslations[lang] = value;
                        }
                    }
                    break;
            }
        }
    }

